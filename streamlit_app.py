def create_pdf(ticker, date, price, int_val, upside, wacc, ltg, exit_m, c_curr):
    buffer = BytesIO()
    c = canvas.Canvas(buffer, pagesize=letter)
    width, height = letter

    # Title
    c.setFont("Helvetica-Bold", 24)
    c.drawString(50, height - 50, f"Valuation Report: {ticker}")
    
    # Header Info
    c.setFont("Helvetica", 12)
    c.drawString(50, height - 80, f"Date: {date}")
    c.drawString(50, height - 100, "Method: Discounted Cash Flow (DCF)")

    # Divider
    c.line(50, height - 110, width - 50, height - 110)

    # --- RESULTS SECTION ---
    c.setFont("Helvetica-Bold", 18)
    c.drawString(50, height - 150, "Valuation Results")

    c.setFont("Helvetica", 14)
    c.drawString(50, height - 180, f"Current Price: {c_curr}{price:,.2f}")
    c.drawString(50, height - 200, f"Intrinsic Value: {c_curr}{int_val:,.2f}")
    
    # Color logic for text (Manual in PDF)
    status = "UNDERVALUED" if upside >= 0 else "OVERVALUED"
    c.drawString(50, height - 220, f"Upside: {upside:+.1%} ({status})")

    # --- ASSUMPTIONS SECTION ---
    c.setFont("Helvetica-Bold", 18)
    c.drawString(50, height - 270, "Key Assumptions")
    
    c.setFont("Helvetica", 12)
    c.drawString(50, height - 300, f"WACC: {wacc:.1%}")
    c.drawString(50, height - 320, f"Terminal Growth (Gordon): {ltg:.1%}")
    c.drawString(50, height - 340, f"Exit Multiple (EBITDA): {exit_m}x")

    # Footer
    c.setFont("Helvetica-Oblique", 10)
    c.drawString(50, 50, "Generated by Python Streamlit DCF Tool")
    
    c.showPage()
    c.save()
    buffer.seek(0)
    return buffer

