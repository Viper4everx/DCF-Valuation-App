def calculate_dcf_value(r_0, e_0, d_0, c_0, g, m, t, w, l, em, debt, cash, shares, years=5):
    if w <= l: l = w - 0.005 
    
    cap_r = c_0/r_0 if r_0 else 0
    dep_r = d_0/r_0 if r_0 else 0
    nwc_r = 0.02
    
    fcf_pv_sum = 0.0
    prev_rev = r_0
    
    last_fcf = 0.0
    last_ebitda = 0.0
    
    for y in range(1, years + 1):
        rev = prev_rev * (1 + g)
        ebit = rev * m
        nopat = ebit * (1 - t)
        da = rev * dep_r
        capex = rev * cap_r
        dnwc = (rev - prev_rev) * nwc_r
        
        fcff = nopat + da - capex - dnwc
        pv = fcff * ((1 + w)**-y)
        fcf_pv_sum += pv
        
        prev_rev = rev
        if y == years:
            last_fcf = fcff
            last_ebitda = ebit + da

    tv_g = last_fcf * (1 + l) / (w - l)
    pv_tv_g = tv_g * ((1 + w)**-years)
    
    tv_e = last_ebitda * em
    pv_tv_e = tv_e * ((1 + w)**-years)
    
    eq_g = (fcf_pv_sum + pv_tv_g) - (debt - cash)
    eq_e = (fcf_pv_sum + pv_tv_e) - (debt - cash)
    
    price_g = eq_g / shares if shares > 0 else 0
    price_e = eq_e / shares if shares > 0 else 0
    
    return (price_g + price_e) / 2

